const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;')
// "# Title" / "## 3. Heading" / paragraphs → printable HTML
export function termsHtml(text) {
  return String(text || '').split(/\n\s*\n/).map(b => b.trim()).filter(Boolean).map(b => {
    if (/^# /.test(b)) return `<h3 style="margin:18px 0 6px">${esc(b.slice(2))}</h3>`
    if (/^## /.test(b)) return `<h4 style="margin:10px 0 3px;font-size:11px">${esc(b.slice(3))}</h4>`
    return `<p style="margin:3px 0;font-size:9.5px;line-height:1.35;text-align:justify">${esc(b)}</p>`
  }).join('')
}
